def require(condition, message):
    if not condition:
        raise ValueError(message)


def sha(path):
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for block in iter(lambda: handle.read(1024*1024), b""):
            digest.update(block)
    return digest.hexdigest()


def markdown_links(path):
    """Inline Markdown destinations, excluding code examples and external URLs."""
    body = path.read_text(encoding="utf-8-sig")
    body = re.sub(r"^```[^\n]*\n.*?^```\s*$", "", body, flags=re.M|re.S)
    body = re.sub(r"`[^`\n]+`", "", body)
    for match in re.finditer(r"!?\[[^\]\n]*\]\(\s*(<[^>]+>|[^)\n]+)\)", body):
        value = match.group(1).strip()
        if value.startswith("<"):
            value = value[1:-1]
        else:
            value = value.split(' "', 1)[0].split(" '", 1)[0]
        if not value or value.startswith("#") or urlsplit(value).scheme:
            continue
        yield unquote(value.split("#",1)[0]).replace("\\", "/")


def check_links(root, documents, *, source_only=False):
    errors, unavailable = [], []
    checked = 0
    for document in documents:
        path = root/document
        for destination in markdown_links(path):
            target = (path.parent/destination).resolve()
            try:
                relative = target.relative_to(root.resolve()).as_posix()
            except ValueError:
                errors.append(f"{document}: link escapes the project: {destination}")
                continue
            checked += 1
            if target.exists():
                continue
            if relative == "docs/delivery_verification.json":
                unavailable.append({"document":document,"target":relative,"reason":"generated by verify --write"})
            elif source_only and relative.startswith(("artifacts/","data/","reports/","submissions/")):
                unavailable.append({"document":document,"target":relative,"reason":"private/generated evidence absent in source-only copy"})
            else:
                errors.append(f"{document}: broken local link: {destination}")
    return {"checked":checked,"errors":errors,"unavailable_evidence_links":unavailable,
            "anchor_validation":False}


def check_facts(facts):
    require(facts["schema_version"] == 1, "Unsupported project fact schema")
    dataset = facts["dataset"]
    expected = {"train_rows":688998,"test_rows":36324,"train_columns":1107,"test_columns":1106,
                "anonymous_numeric_features":1105,"repayment_label":1,"default_label":0}
    for field,value in expected.items():
        require(type(dataset[field]) is int and dataset[field] == value, f"Dataset fact mismatch: {field}")
    for field in ("test_labels_available","id_is_model_feature","verified_training_time_order"):
        require(dataset[field] is False, f"Unsupported dataset claim: {field}")
    require(facts["validation"]["reused_development_oof"] is True, "OOF reuse must be disclosed")
    require(facts["validation"]["probability_calibrated"] is False, "Calibration is not delivered")
    models = {model["model_role"]:model for model in facts["models"]}
    require(set(models) == {"champion","challenger"} and len(facts["models"]) == 2, "Invalid frozen model registry")
    for role,version,count in (("champion","lightgbm_baseline",5),("challenger","lightgbm_tuned_seed_ensemble",15)):
        require(models[role]["model_version"] == version and models[role]["refit_models"] == count, "Frozen model identity changed")
        require(models[role]["feature_count"] == 1105, "Frozen feature count changed")
        for field in ("repay_roc_auc","default_pr_auc_ap","ks","brier_score","threshold"):
            value = models[role][field]
            require(isinstance(value,(float,int)) and math.isfinite(value) and 0 <= value <= 1, f"Invalid metric: {role}/{field}")
    experiment = facts["experiment"]
    require(experiment["champion_retained"] is True, "Champion must be retained")
    for field in ("challenger_promoted","live_experiment_completed","production_rollout_ready","live_outcome_maturity_validated"):
        require(experiment[field] is False, f"Unsupported promotion/live claim: {field}")
    require(all(value is None for value in facts["unknown_live_results"].values()), "Unknown live results must remain NULL")
    require(experiment["randomized_disagreements"] == 12614 and experiment["full_eligible_evaluation_rows"] == 210856,
            "Evaluation denominators changed")
    require(experiment["protocol"]["required_randomized_disagreements"] == 17141, "Fixed sample changed")
    replay = experiment["replay"]
    require(replay["ci_low"] <= replay["delta"] <= replay["ci_high"], "Invalid profit interval")
    require(replay["business_threshold"] == 5 and replay["ci_low"] < 5 and replay["business_value_demonstrated_in_simulation"] is False,
            "Business lower-bound decision changed")
    require(facts["aa"]["original_uncertified_checks"] == 6 and facts["aa"]["v2_matched_checks"] == 20,
            "Calibration scope changed")
    return {"status":"passed","unknown_live_values_preserved":True,"frozen_decision_and_denominators_verified":True}


def check_claims(root, facts):
    errors = []
    models = {m["model_role"]:m for m in facts["models"]}
    exp = facts["experiment"]
    interval = [f'{exp["replay"][field]:.3f}' for field in ("delta","ci_low","ci_high")]
    common = ["688,998", "36,324", "1,105", *interval, "OOF", "Champion"]
    for document in CLAIM_DOCS:
        body = (root/document).read_text(encoding="utf-8")
        words = list(common) if "experiment_card" not in document else ["12,614","17,141","210,856",*interval,"OOF","NULL"]
        if document.startswith("README") or "model_card" in document:
            words += [f'{models[role][field]:.6f}' for role in ("champion","challenger")
                      for field in ("repay_roc_auc","default_pr_auc_ap","ks")]
        if "model_card" in document:
            words += [f'{models[role][field]:.6f}' for role in ("champion","challenger")
                      for field in ("log_loss","brier_score")]
        if document.startswith("README") or "experiment_card" in document:
            words += [str(exp["primary_assumed_enrollment_days"]),str(exp["primary_assumed_final_analysis_days"]),"14.20%","4.934%","90.53%"]
        for word in words:
            if word not in body:
                errors.append(f"{document}: missing displayed claim/boundary {word}")
        tokens = ("historical","simulat","retain","not") if document.endswith(".en.md") else ("历史","模拟","保留","未")
        for token in tokens:
            if token not in body.lower():
                errors.append(f"{document}: missing evidence boundary {token}")
    return errors


def check_sources(root, facts):
    checked, missing, errors = [], [], []
    for name,digest in facts["sources_sha256"].items():
        path = (root/name).resolve()
        if not path.is_relative_to(root.resolve()):
            errors.append(f"Source path escapes project: {name}")
            continue
        if not re.fullmatch(r"[a-f0-9]{64}",digest):
            errors.append(f"Invalid SHA-256: {name}")
        elif not path.is_file():
            missing.append(name)
        elif sha(path) != digest:
            errors.append(f"Source hash mismatch: {name}")
        else:
            checked.append(name)
    if not missing and not errors:
        from scripts.build_project_facts import collect
        try:
            require(collect(root) == facts, "Fact snapshot differs from available source summaries")
        except (AssertionError, ValueError, KeyError) as exc:
            errors.append(str(exc))
    return {"available_checked":checked,"unavailable":missing,"errors":errors,
            "fact_recollection_performed":not missing and not errors,
            "note":"Hash checks/recollection do not rerun model fitting or full statistical calibration."}


def check_architecture(path):
    element = ET.parse(path).getroot()
    require(element.tag == "{http://www.w3.org/2000/svg}svg", "Architecture is not SVG")
    require(element.get("viewBox") == "0 0 1600 1100", "Unexpected architecture bounds")
    words = " ".join(element.itertext())
    require("Retain Champion" in words and "NOT IMPLEMENTED" in words and "full-eligible ITT" in words,
            "Architecture loses the decision, ITT or live boundary")
    return {"xml_valid":True,"decision_itt_and_live_boundary_present":True,
            "visual_review_basis":"Matching PNG reviewed locally; Mermaid source provided in architecture.md."}


def verify(root=ROOT):
    root = Path(root)
    required = [*REQUIRED_DOCS,"requirements.txt","requirements-lock.txt","scripts/project.py",
                "scripts/replay_frozen_business.py","scripts/verify_project_delivery.py",
                "scripts/render_project_architecture.py","docs/figures/architecture.png","tests/test_project_delivery.py",
                "dashboard/powerbi/README.md"]
    errors = [f"Missing delivery file: {name}" for name in required if not (root/name).is_file()]
    if errors:
        return {"status":"failed","errors":errors}
    documents = ["README.md","README.en.md",*[p.relative_to(root).as_posix() for p in sorted((root/"docs").glob("*.md"))],
                 "dashboard/powerbi/README.md"]
    source_only = not (root/"artifacts").exists()
    links = check_links(root,documents,source_only=source_only)
    errors.extend(links["errors"])
    facts = json.loads((root/"docs/project_facts.json").read_text(encoding="utf-8"))
    try:
        facts_check = check_facts(facts)
        errors.extend(check_claims(root,facts))
        sources = check_sources(root,facts)
        errors.extend(sources["errors"])
        architecture = check_architecture(root/"docs/figures/architecture.svg")
    except (ValueError,KeyError,ET.ParseError) as exc:
        errors.append(str(exc))
        facts_check,sources,architecture = {},{},{}
    referenced_scripts = sorted({args[0] for steps in [*PIPELINES.values(),*VERIFY.values()] for args in steps})
    for name in referenced_scripts:
        if not (root/name).is_file():
            errors.append(f"CLI pipeline missing script: {name}")
    return {"status":"passed" if not errors else "failed","scope":"documentation_claims_links_and_available_source_hashes",
            "source_only_copy":source_only,"documents_checked":documents,"links":links,
            "facts":facts_check,"source_provenance":sources,"architecture":architecture,
            "cli_scripts_checked":referenced_scripts,"business_freeze_stages":list(BUSINESS_STAGES),
            "model_training_performed":False,"full_statistical_replay_performed":False,
            "historical_audit_files_written":False,"desktop_all_pages_verified":False,"errors":errors}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write",action="store_true")
    args = parser.parse_args()
    result = verify()
    if args.write:
        (ROOT/"docs/delivery_verification.json").write_text(json.dumps(result,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    print(json.dumps(result,ensure_ascii=False,indent=2))
    return 0 if result["status"] == "passed" else 2


if __name__ == "__main__":
    raise SystemExit(main())
